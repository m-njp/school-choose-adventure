import 'package:flutter/material.dart';
import 'package:google_fonts/google_fonts.dart';
import 'StoryBrain.dart';

import 'package:audioplayers/audioplayers.dart';

StoryBrain storyBrain = StoryBrain();

void main() => runApp(const ChooseAdventure());

class ChooseAdventure extends StatelessWidget {
  const ChooseAdventure({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      theme: ThemeData(
        textTheme: GoogleFonts.jersey10TextTheme(),
        colorScheme: const ColorScheme.dark(),
      ),
      home: Scaffold(
        backgroundColor: Colors.grey.shade900,
        appBar: AppBar(
          backgroundColor: Colors.blueGrey.shade900,
          title: const Text('THE QUIET', style: TextStyle(letterSpacing: 3)),
        ),
        body: const SafeArea(
          child: Padding(
            padding: EdgeInsets.symmetric(horizontal: 10.0),
            child: StoryPage(),
          ),
        ),
      ),
    );
  }
}

class StoryPage extends StatefulWidget {
  const StoryPage({super.key});

  @override
  State<StoryPage> createState() => _StoryPageState();
}

class _StoryPageState extends State<StoryPage> {
  final AudioPlayer _audioPlayer = AudioPlayer();

  @override
  void initState() {
    super.initState();
    _updateAudio();
  }

  @override
  void dispose() {
    _audioPlayer.dispose();
    super.dispose();
  }

  void _updateAudio() async {
    await _audioPlayer.stop();
    String? audioPath = storyBrain.getSceneAudio();
    if (audioPath != null) {
      _audioPlayer.setReleaseMode(ReleaseMode.loop);
      await _audioPlayer.play(AssetSource(audioPath.replaceFirst('assets/', '')));
    }
  }

  void makeChoice(int choiceIndex) {
    setState(() {
      storyBrain.nextScene(choiceIndex);
    });
    _updateAudio();
  }

  List<Widget> buildChoiceButtons() {
    if (storyBrain.isGameOver()) {
      return [
        Padding(
          padding: const EdgeInsets.only(bottom: 6.0),
          child: Text(
            storyBrain.getEndingType().toUpperCase(),
            textAlign: TextAlign.center,
            style: const TextStyle(color: Colors.blueGrey, fontSize: 16.0, letterSpacing: 2),
          ),
        ),
        TextButton(
          style: TextButton.styleFrom(
            backgroundColor: Colors.blueGrey,
            shape: const RoundedRectangleBorder(borderRadius: BorderRadius.zero),
            padding: const EdgeInsets.all(14.0),
          ),
          onPressed: () {
            setState(() => storyBrain.restart());
            _updateAudio();
          },
          child: const Text(
            'PLAY AGAIN',
            textAlign: TextAlign.center,
            style: TextStyle(color: Colors.white, fontSize: 18.0),
          ),
        ),
      ];
    }

    final List<String> choices = storyBrain.getChoices();

    return List.generate(choices.length, (i) {
      return Padding(
        padding: const EdgeInsets.symmetric(vertical: 4.0),
        child: TextButton(
          style: TextButton.styleFrom(
            backgroundColor: Colors.blueGrey,
            shape: const RoundedRectangleBorder(
              borderRadius: BorderRadius.zero,
            ),
            padding: const EdgeInsets.all(14.0),
          ),
          onPressed: () => makeChoice(i),
          child: Text(
            choices[i],
            textAlign: TextAlign.center,
            style: const TextStyle(color: Colors.white, fontSize: 18.0),
          ),
        ),
      );
    });
  }

  @override
  Widget build(BuildContext context) {
    return Column(
      mainAxisAlignment: MainAxisAlignment.spaceBetween,
      crossAxisAlignment: CrossAxisAlignment.stretch,
      children: <Widget>[
        Expanded(
          flex: 3,
          child: Padding(
            padding: const EdgeInsets.all(10.0),
            child: Column(
              children: [
                Expanded(
                  child: Image.asset(storyBrain.getSceneImage(), fit: BoxFit.cover),
                ),
                const SizedBox(height: 8),
                const Text(
                  'Photo generated by Gemini Banana Pro 3',
                  style: TextStyle(
                    fontFamily: 'Roboto',
                    fontStyle: FontStyle.italic,
                    fontSize: 12.0,
                    color: Colors.white54,
                  ),
                ),
              ],
            ),
          ),
        ),

        Expanded(
          flex: 4,
          child: Padding(
            padding: const EdgeInsets.all(10.0),
            child: SingleChildScrollView(
              child: Text(
                storyBrain.getStoryText(),
                textAlign: TextAlign.left,
                style: const TextStyle(
                  fontSize: 21.0,
                  color: Colors.white,
                  height: 1.5,
                ),
              ),
            ),
          ),
        ),

        Column(
          crossAxisAlignment: CrossAxisAlignment.stretch,
          children: buildChoiceButtons(),
        ),
      ],
    );
  }
}
